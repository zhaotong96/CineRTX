std::string deriveOutputPath(std::string_view input_path,
                             std::string_view codec,
                             std::string_view current_output,
                             bool auto_output) {
    const std::string trimmed_in = std::string(rtx::str::trimAscii(input_path));
    const std::string trimmed_out = std::string(rtx::str::trimAscii(current_output));
    if (!trimmed_out.empty() && (!auto_output || !isAutoGeneratedOutputName(trimmed_out))) {
        return trimmed_out;
    }
    if (trimmed_in.empty()) {
        return trimmed_out;
    }
    std::string norm_codec = "av1";
    const std::string lower = rtx::str::toLowerAscii(codec);
    if (lower == "hevc" || lower == "h265") {
        norm_codec = "hevc";
    }
    const std::filesystem::path in = rtx::str::utf8ToPath(trimmed_in);
    const std::filesystem::path stem = in.stem();
    const std::string out_name = rtx::str::pathToUtf8(stem) + "_remaster_" + norm_codec + ".mp4";
    const std::filesystem::path out = in.has_parent_path() ? (in.parent_path() / rtx::str::utf8ToPath(out_name))
                                                           : rtx::str::utf8ToPath(out_name);
    return rtx::str::pathToUtf8(out);
}
std::filesystem::path resolveDefaultRifeEnginePath(std::string_view explicit_path) {
    const std::string trimmed = std::string(rtx::str::trimAscii(explicit_path));
    if (!trimmed.empty()) {
        return rtx::str::utf8ToPath(trimmed);
    }
    const std::filesystem::path exe_dir = executableDirectory();
    const std::filesystem::path candidates[] = {
        exe_dir / "models" / "rife_v4.25.engine",
        exe_dir / "models" / "rife_v4.25_wide.engine",
        exe_dir / "models" / "rife_v4.25_ultra.engine",
        exe_dir / "models" / "rife_v4.25_square.engine",
        exe_dir / "models" / "rife_v4.25_tall.engine",
        exe_dir / "models" / "rife_v4.25_landscape.engine",
        exe_dir / "models" / "rife_v4.25_portrait.engine",
        std::filesystem::path("models") / "rife_v4.25.engine",
        std::filesystem::path("models") / "rife_v4.25_wide.engine",
        std::filesystem::path("models") / "rife_v4.25_ultra.engine",
        std::filesystem::path("models") / "rife_v4.25_square.engine",
        std::filesystem::path("models") / "rife_v4.25_tall.engine",
        std::filesystem::path("models") / "rife_v4.25_landscape.engine",
        std::filesystem::path("models") / "rife_v4.25_portrait.engine",
        exe_dir / "rife.engine",
        std::filesystem::path("rife.engine"),
    };
    std::error_code ec;
    for (const auto& candidate : candidates) {
        if (!candidate.empty() && std::filesystem::exists(candidate, ec) && !ec) {
            return candidate;
        }
    }
    return exe_dir.empty() ? (std::filesystem::path("models") / "rife_v4.25.engine")
                           : (exe_dir / "models" / "rife_v4.25.engine");
}
Result<void> validateAndNormalizeProfile(TranscodeProfile& profile, bool require_io_paths) {
    forEachProfileField(profile, [](const ParamMeta& meta, auto& field) {
        const auto& [jk, cf, kd, lb, mn, mx, di, db, ds, ec, nl] = meta;
        (void)jk; (void)cf; (void)kd; (void)lb; (void)mn; (void)mx; (void)di; (void)db; (void)ds; (void)ec;
        if constexpr (std::is_same_v<std::decay_t<decltype(field)>, std::string>) {
            field = nl ? rtx::str::toLowerAscii(rtx::str::trimAscii(field)) : rtx::str::trimAscii(field);
        }
    });

    // Wave 1-B: av1_cpu (libsvtav1) & hevc_cpu (libx265) CRF unlocked.
    if (profile.codec == "h264" || profile.codec == "avc" || profile.codec == "2") {
        return err(ErrorCode::InvalidArgument,
                   "profile.codec 'h264' (8-bit SDR) is not supported by the 10-bit HDR10 remaster pipeline; use 'av1' or 'hevc'");
    }
    if (profile.codec.empty() || profile.codec == "0") {
        profile.codec = "av1";
    } else if (profile.codec == "h265" || profile.codec == "1") {
        profile.codec = "hevc";
    }
    if (profile.pipeline_order.empty()) {
        profile.pipeline_order = "vsr-first";
    }
    if (profile.rate_control.empty() || profile.rate_control == "0") {
        profile.rate_control = "cq";
    } else if (profile.rate_control == "1") {
        profile.rate_control = "vbr";
    } else if (profile.rate_control == "constqp" || profile.rate_control == "2") {
        profile.rate_control = "qp";
    } else if (profile.rate_control == "3") {
        profile.rate_control = "cq";
    } else if (profile.rate_control == "4") {
        profile.rate_control = "crf";
    }
    if (profile.rate_control == "crf" && profile.codec != "av1_cpu" && profile.codec != "hevc_cpu") {
        profile.rate_control = "cq";
    }
    if (profile.resolution.empty()) {
        profile.resolution = "4k";
    }
    if (profile.geometry.empty()) {
        profile.geometry = "auto";
    }
    if (profile.fps_mode.empty()) {
        profile.fps_mode = "60-nvofa";
    }
    Result<void> validation_result{};
    forEachProfileField(profile, [&](const ParamMeta& meta, const auto& field) {
        if (!validation_result.has_value()) return;
        const auto& [json_key, cf, kind, lb, min_val, max_val, di, db, ds, enum_csv, nl] = meta;
        (void)cf; (void)lb; (void)di; (void)db; (void)ds; (void)nl;
        using T = std::decay_t<decltype(field)>;
        if constexpr (std::is_same_v<T, int>) {
            if (min_val != max_val && (field < min_val || field > max_val)) {
                validation_result = err(
                    ErrorCode::InvalidArgument,
                    std::format("profile.{} must be in {}..{}", json_key, min_val, max_val));
                return;
            }
        } else if constexpr (std::is_same_v<T, std::string>) {
            if (kind == ParamKind::Enum && !enum_csv.empty()) {
                bool matched = false;
                std::string_view csv = enum_csv;
                while (!csv.empty()) {
                    const size_t comma = csv.find(',');
                    const std::string_view token = (comma == std::string_view::npos) ? csv : csv.substr(0, comma);
                    if (field == token) { matched = true; break; }
                    if (comma == std::string_view::npos) break;
                    csv.remove_prefix(comma + 1);
                }
                if (!matched) {
                    validation_result = err(
                        ErrorCode::InvalidArgument,
                        std::format("profile.{} must be one of [{}]", json_key, enum_csv));
                    return;
                }
            }
        }
    });
    if (!validation_result.has_value()) return validation_result;

    if (profile.resolution == "4k") {
        profile.target_width = 3840;
        profile.target_height = 2160;
    } else if (profile.resolution == "2k") {
        profile.target_width = 2560;
        profile.target_height = 1440;
    } else if (profile.resolution == "fhd") {
        profile.target_width = 1920;
        profile.target_height = 1080;
    } else if (profile.resolution == "native") {
        profile.target_width = 0;
        profile.target_height = 0;
    }
    if (profile.target_width < 0 || profile.target_height < 0) {
        return err(ErrorCode::InvalidArgument, "target geometry must be non-negative");
    }
    if (profile.fps_mode == "60-rife" || profile.fps_mode == "120-rife") {
        const std::filesystem::path resolved_rife = resolveDefaultRifeEnginePath(profile.rife_engine);
        profile.rife_engine = rtx::str::pathToUtf8(resolved_rife);
    }
    profile.output = deriveOutputPath(profile.input, profile.codec, profile.output, profile.auto_output);

    if (require_io_paths) {
        if (profile.input.empty()) {
            return err(ErrorCode::InvalidArgument, "profile.input is required");
        }
        if (profile.output.empty()) {
            return err(ErrorCode::InvalidArgument, "profile.output is required");
        }
        if (profile.input == profile.output) {
            return err(ErrorCode::InvalidArgument,
                       "input and output paths must not be identical");
        }
    }
    return {};
}
HwTranscodeOptions profileToHwOptions(const TranscodeProfile& profile) {
    const bool is_cpu = (profile.codec == "av1_cpu" || profile.codec == "hevc_cpu");
    const VideoCodec codec = (profile.codec == "hevc" || profile.codec == "hevc_cpu") ? VideoCodec::HEVC : VideoCodec::AV1;
    int rc = 3;
    if (profile.rate_control == "cq") {
        rc = 3;

    } else if (profile.rate_control == "qp") {
        rc = 2;
    } else if (profile.rate_control == "vbr") {
        rc = 1;
    } else if (profile.rate_control == "cbr") {
        rc = 0;
    } else if (profile.rate_control == "crf") {
        rc = 4;
    }
    const int geom = (profile.geometry == "pillarbox") ? 1 : 0;
    const bool vsr_before_fg = (profile.pipeline_order != "fg-first");

    bool fruc = true;
    Rational fps{60, 1};
    std::filesystem::path rife_path;
    if (profile.fps_mode == "original") {
        fruc = false;
        fps = Rational{0, 1};
    } else if (profile.fps_mode == "120-nvofa") {
        fruc = true;
        fps = Rational{120, 1};
    } else if (profile.fps_mode == "60-rife") {
        fruc = true;
        fps = Rational{60, 1};
        rife_path = resolveDefaultRifeEnginePath(profile.rife_engine);
    } else if (profile.fps_mode == "120-rife") {
        fruc = true;
        fps = Rational{120, 1};
        rife_path = resolveDefaultRifeEnginePath(profile.rife_engine);
    } else {
        fruc = true;
        fps = Rational{60, 1};
        if (!profile.rife_engine.empty()) {
            rife_path = rtx::str::utf8ToPath(profile.rife_engine);
        }
    }
    return HwTranscodeOptions{
        .input_path = rtx::str::utf8ToPath(profile.input),
        .output_path = rtx::str::utf8ToPath(profile.output),
        .frame_limit = profile.frames,
        .codec = codec,
        .use_cpu_encoder = is_cpu,
        .cpu_preset = std::to_string(profile.preset),
        .bitrate_kbps = profile.bitrate_kbps,
        .preset = profile.preset,
        .rate_control = rc,
        .qp = profile.qp,
        .copy_audio = profile.copy_audio,
        .vsr_before_fg = vsr_before_fg,
        .hdr10plus = profile.hdr10plus,
        .lut_path = profile.lut.empty() ? std::filesystem::path{} : rtx::str::utf8ToPath(profile.lut),
        .target_width = profile.target_width,
        .target_height = profile.target_height,
        .vsr_enabled = profile.vsr_enabled,
        .vsr_quality = profile.vsr_quality,
        .peak_nits = profile.peak_nits,
        .geometry_mode = geom,
        .device_index = profile.gpu,
        .fruc_enabled = fruc,
        .target_fps = fps,
        .rife_engine_path = std::move(rife_path),
    };
}
Result<TranscodeProfile> parseProfileFromJson(std::string_view json_text) {
    const std::string trimmed(rtx::str::trimAscii(json_text));
    size_t pos = 0;
    auto root = rtx::json::scanObject(trimmed, pos);
    if (!root.has_value()) return std::unexpected(root.error());
    rtx::json::skipWs(trimmed, pos);
    if (pos != trimmed.size()) {
        return err(ErrorCode::InvalidArgument, "JSON payload must be a single object");
    }
    TranscodeProfile p{};
    auto ui = jsonChildObject(*root, "ui");
    if (!ui.has_value()) return std::unexpected(ui.error());
    if (!ui->empty()) {
        bool auto_out = true;
        auto r = jsonMemberBool(*ui, "autoOutput", auto_out);
        if (!r.has_value()) return std::unexpected(r.error());
        if (r.value()) p.auto_output = auto_out;

        std::string lang_str;
        auto lr = jsonMemberString(*ui, "lang", lang_str);
        if (!lr.has_value()) return std::unexpected(lr.error());
        if (lr.value()) {
            if (auto parsed_lang = parseLanguage(lang_str); parsed_lang.has_value()) {
                setLanguage(parsed_lang.value());
            }
        }
    }
    std::vector<std::pair<std::string, std::string_view>> scope;
    if (rtx::json::findMember(*root, "profile") != nullptr) {
        auto child = jsonChildObject(*root, "profile");
        if (!child.has_value()) return std::unexpected(child.error());
        scope = std::move(*child);
    } else {
        scope = std::move(*root);
    }
    Result<void> applied{};
    forEachProfileField(p, [&](const ParamMeta& meta, auto& field) {
        if (!applied.has_value()) return;
        const auto& [json_key, cf, kd, lb, mn, mx, di, db, ds, ec, nl] = meta;
        (void)cf; (void)kd; (void)lb; (void)mn; (void)mx; (void)di; (void)db; (void)ds; (void)ec; (void)nl;
        using T = std::decay_t<decltype(field)>;
        if constexpr (std::is_same_v<T, std::string>) {
            std::string value;
            auto r = jsonMemberString(scope, json_key, value);
            if (!r.has_value()) { applied = std::unexpected(r.error()); return; }
            if (r.value()) field = std::move(value);
        } else if constexpr (std::is_same_v<T, int>) {
            int value = 0;
            auto r = jsonMemberInt(scope, json_key, value);
            if (!r.has_value()) { applied = std::unexpected(r.error()); return; }
            if (r.value()) field = value;
        } else {
            bool value = false;
            auto r = jsonMemberBool(scope, json_key, value);
            if (!r.has_value()) { applied = std::unexpected(r.error()); return; }
            if (r.value()) field = value;
        }
    });
    if (!applied.has_value()) return std::unexpected(applied.error());

    if (auto r = jsonMemberBool(scope, "autoOutput", p.auto_output); !r.has_value()) {
        return std::unexpected(r.error());
    }
    return p;
}
std::string profileToJson(const TranscodeProfile& p) {
    std::string out = "{\n";
    bool first = true;
    forEachProfileField(p, [&](const ParamMeta& meta, const auto& value) {
        const auto& [json_key, cf, kd, lb, mn, mx, di, db, ds, ec, nl] = meta;
        (void)cf; (void)kd; (void)lb; (void)mn; (void)mx; (void)di; (void)db; (void)ds; (void)ec; (void)nl;
        if (!first) out += ",\n";
        first = false;
        out += std::format("    \"{}\": ", json_key);
        using T = std::decay_t<decltype(value)>;
        if constexpr (std::is_same_v<T, std::string>) {
            out += '"' + rtx::json::escapeJson(value) + '"';
        } else if constexpr (std::is_same_v<T, bool>) {
            out += value ? "true" : "false";
        } else {
            out += std::to_string(value);
        }
    });
    out += "\n  }";
    return out;
}
std::string exportSchemaJson() {
    const TranscodeProfile defaults{};
    std::string out = "{\n  \"version\": 1,\n  \"defaults\": ";
    out += profileToJson(defaults);
    out += ",\n  \"params\": [\n";
    for (size_t i = 0; i < kParamDescriptors.size(); ++i) {
        const auto& [m_key, m_cli, m_kind, m_lbl, m_min, m_max, m_di, m_db, m_ds, m_csv, m_low] = kParamDescriptors[i].first;
        (void)m_low;
        const char* kind_str = (m_kind == ParamKind::Int) ? "int"
                             : (m_kind == ParamKind::Bool) ? "bool"
                             : (m_kind == ParamKind::Enum) ? "enum" : "string";
        out += std::format(
            "    {{\"key\": \"{}\", \"cli\": \"{}\", \"type\": \"{}\", \"labelId\": \"{}\"",
            m_key, m_cli, kind_str, strIdName(m_lbl));
        if (m_kind == ParamKind::Int) {
            out += std::format(", \"min\": {}, \"max\": {}, \"default\": {}",
                               m_min, m_max, m_di);
        } else if (m_kind == ParamKind::Bool) {
            out += std::format(", \"default\": {}", m_db ? "true" : "false");
        } else if (m_kind == ParamKind::Enum) {
            out += std::format(", \"default\": \"{}\", \"options\": [", m_ds);
            std::string_view csv = m_csv;
            bool first = true;
            while (!csv.empty()) {
                const size_t comma = csv.find(',');
                const std::string_view token = (comma == std::string_view::npos) ? csv : csv.substr(0, comma);
                if (!first) out += ", ";
                out += std::format("\"{}\"", token);
                first = false;
                if (comma == std::string_view::npos) break;
                csv.remove_prefix(comma + 1);
            }
            out += "]";
        } else {
            out += std::format(", \"default\": \"{}\"", m_ds);
        }
        out += (i + 1 < kParamDescriptors.size()) ? "},\n" : "}\n";
    }
    out += "  ],\n  \"i18n\": ";
    out += exportI18nJson();
    out += "\n}\n";
    return out;
}

std::string formatCliHelp() {
    std::string out = "Schema-driven options (SSOT kParamDescriptors):\n";
    for (const auto& [meta, ptr] : kParamDescriptors) {
        (void)ptr;
        const auto& [jk, cli_flag, kind, label_id, min_val, max_val, default_int, default_bool, default_str, enum_csv, nl] = meta;
        (void)jk; (void)nl;
        if (cli_flag.empty()) continue;
        std::string constraint;
        switch (kind) {
            case ParamKind::Int:
                constraint = std::format("[{}..{}, default={}]", min_val, max_val, default_int);
                break;
            case ParamKind::Enum:
                constraint = std::format("{{{}, default={}}}", enum_csv, default_str);
                break;
            case ParamKind::Bool:
                constraint = std::format("[bool, default={}]", default_bool ? "true" : "false");
                break;
            case ParamKind::String:
                constraint = "[string]";
                break;
        }
        out += std::format("  {:18} {:32} {}\n", cli_flag, constraint, tr(label_id));
    }
    return out;
}

