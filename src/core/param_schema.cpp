std::filesystem::path executableDirectory() {
#if defined(_WIN32)
    wchar_t buffer[MAX_PATH] = {};
    const DWORD len = ::GetModuleFileNameW(nullptr, buffer, MAX_PATH);
    if (len > 0 && len < MAX_PATH) {
        return std::filesystem::path(buffer).parent_path();
    }
#endif
    std::error_code ec;
    const auto cwd = std::filesystem::current_path(ec);
    return ec ? std::filesystem::path{} : cwd;
}
bool isAutoGeneratedOutputName(std::string_view path_str) {
    if (path_str.empty()) {
        return true;
    }
    const std::filesystem::path p = rtx::str::utf8ToPath(path_str);
    const std::string filename = rtx::str::toLowerAscii(rtx::str::pathToUtf8(p.filename()));
    static constexpr std::string_view kSuffixes[] = {
        "_remaster_av1.mp4",      "_remaster_hevc.mp4",      "_remaster_h264.mp4",
        "_remaster_av1.mkv",      "_remaster_hevc.mkv",      "_remaster_h264.mkv",
    };
    for (std::string_view suffix : kSuffixes) {
        if (filename.size() > suffix.size() &&
            filename.compare(filename.size() - suffix.size(), suffix.size(), suffix) == 0) {
            return true;
        }
    }
    return false;
}
Result<bool> jsonMemberString(const std::vector<std::pair<std::string, std::string_view>>& members, std::string_view key,
                              std::string& out) {
    const std::pair<std::string, std::string_view>* m = rtx::json::findMember(members, key);
    if (m == nullptr) return false;
    if (m->second == "null") return false;
    if (m->second.empty() || m->second.front() != '"') {
        return err(ErrorCode::InvalidArgument, std::format("profile.{} must be a string", key));
    }
    auto decoded = rtx::json::decodeString(m->second);
    if (!decoded.has_value()) return std::unexpected(decoded.error());
    out = std::move(*decoded);
    return true;
}
Result<bool> jsonMemberInt(const std::vector<std::pair<std::string, std::string_view>>& members, std::string_view key, int& out) {
// Phase 11.2 (A-03): decodeString 依旧校验每个转义；失败必须传播，
// 绝不允许被默认值吞掉（否则 "\u00ZZ" 这类负载会被静默接受）。
    const std::pair<std::string, std::string_view>* m = rtx::json::findMember(members, key);
    if (m == nullptr) return false;
    if (m->second == "null") return false;
    std::string_view token = m->second;
    if (!token.empty() && token.front() == '"') {
        if (token.size() < 2 || token.back() != '"') {
            return err(ErrorCode::InvalidArgument, std::format("profile.{} must be an integer", key));
        }
        token = token.substr(1, token.size() - 2);
    }
    int parsed = 0;
    const auto [ptr, ec] = std::from_chars(token.data(), token.data() + token.size(), parsed);
    if (ec != std::errc{} || ptr != token.data() + token.size()) {
        return err(ErrorCode::InvalidArgument, std::format("profile.{} must be an integer", key));
    }
    out = parsed;
    return true;
}
Result<bool> jsonMemberBool(const std::vector<std::pair<std::string, std::string_view>>& members, std::string_view key, bool& out) {
    const std::pair<std::string, std::string_view>* m = rtx::json::findMember(members, key);
    if (m == nullptr) return false;
    if (m->second == "null") return false;
    if (m->second == "true" || m->second == "1") {
        out = true;
        return true;
    }
    if (m->second == "false" || m->second == "0") {
        out = false;
        return true;
    }
    return err(ErrorCode::InvalidArgument, std::format("profile.{} must be a boolean", key));
}
Result<std::vector<std::pair<std::string, std::string_view>>> jsonChildObject(const std::vector<std::pair<std::string, std::string_view>>& members,
                                                std::string_view key) {
    const std::pair<std::string, std::string_view>* m = rtx::json::findMember(members, key);
    if (m == nullptr) return std::vector<std::pair<std::string, std::string_view>>{};
    size_t pos = 0;
    auto child = rtx::json::scanObject(m->second, pos);
    if (!child.has_value()) return std::unexpected(child.error());
    rtx::json::skipWs(m->second, pos);
    if (pos != m->second.size()) {
        return err(ErrorCode::InvalidArgument, std::format("profile.{} must be a single object", key));
    }
    return *child;
}
