std::string deriveOutputPath(std::string_view input_path,
                             std::string_view codec,
                             std::string_view current_output,
                             bool auto_output) {
    const std::string trimmed_in = trimAscii(input_path);
    const std::string trimmed_out = trimAscii(current_output);
    if (!trimmed_out.empty() && (!auto_output || !isAutoGeneratedOutputName(trimmed_out))) {
        return trimmed_out;
    }
    if (trimmed_in.empty()) {
        return trimmed_out;
    }
    std::string norm_codec = "av1";
    const std::string lower = toLowerAscii(codec);
    if (lower == "hevc" || lower == "h265") {
        norm_codec = "hevc";
    } else if (lower == "av1_cpu") {
        norm_codec = "av1_cpu";
    } else if (lower == "hevc_cpu") {
        norm_codec = "hevc_cpu";
    }
    const std::filesystem::path in = utf8ToPath(trimmed_in);
    const std::filesystem::path stem = in.stem();
    const std::string out_name = pathToUtf8(stem) + "_remaster_" + norm_codec + ".mp4";
    const std::filesystem::path out = in.has_parent_path() ? (in.parent_path() / utf8ToPath(out_name))
                                                           : utf8ToPath(out_name);
    return pathToUtf8(out);
}

std::filesystem::path resolveDefaultRifeEnginePath(std::string_view explicit_path) {
    const std::string trimmed = trimAscii(explicit_path);
    if (!trimmed.empty()) {
        return utf8ToPath(trimmed);
    }
    const std::filesystem::path exe_dir = executableDirectory();
    const std::filesystem::path candidates[] = {
        exe_dir / "models" / "rife_v4.25.engine",
        std::filesystem::path("models") / "rife_v4.25.engine",
        exe_dir / "rife.engine",
        std::filesystem::path("rife.engine"),
    };
    std::error_code ec;
    for (const auto& candidate : candidates) {
        if (!candidate.empty() && std::filesystem::exists(candidate, ec) && !ec) {
            return candidate;
        }
    }
    return exe_dir.empty() ? (std::filesystem::path("models") / "rife_v4.25.engine")
                           : (exe_dir / "models" / "rife_v4.25.engine");
}

Result<void> validateAndNormalizeProfile(TranscodeProfile& profile, bool require_io_paths) {
    profile.input = trimAscii(profile.input);
    profile.output = trimAscii(profile.output);
    profile.codec = toLowerAscii(trimAscii(profile.codec));
    profile.rate_control = toLowerAscii(trimAscii(profile.rate_control));
    profile.resolution = toLowerAscii(trimAscii(profile.resolution));
    profile.geometry = toLowerAscii(trimAscii(profile.geometry));
    profile.fps_mode = toLowerAscii(trimAscii(profile.fps_mode));
    profile.pipeline_order = toLowerAscii(trimAscii(profile.pipeline_order));
    profile.rife_engine = trimAscii(profile.rife_engine);
    profile.lut = trimAscii(profile.lut);

    if (profile.pipeline_order.empty()) {
        profile.pipeline_order = "vsr-first";
    }
    if (profile.pipeline_order != "vsr-first" && profile.pipeline_order != "fg-first") {
        return err(ErrorCode::InvalidArgument,
                   "profile.pipelineOrder must be one of ['vsr-first', 'fg-first']");
    }

    if (profile.codec.empty() || profile.codec == "0") {
        profile.codec = "av1";
    } else if (profile.codec == "h265" || profile.codec == "1") {
        profile.codec = "hevc";
    } else if (profile.codec == "h264" || profile.codec == "avc" || profile.codec == "2") {
        return err(ErrorCode::InvalidArgument,
                   "profile.codec 'h264' (8-bit SDR) is not supported by the 10-bit HDR10 remaster pipeline; use 'av1' or 'hevc'");
    }
    if (profile.codec != "av1" && profile.codec != "hevc" &&
        profile.codec != "av1_cpu" && profile.codec != "hevc_cpu") {
        return err(ErrorCode::InvalidArgument,
                   "profile.codec must be one of ['av1', 'hevc', 'av1_cpu', 'hevc_cpu']");
    }

    const bool is_cpu_codec = (profile.codec == "av1_cpu" || profile.codec == "hevc_cpu");
    if (is_cpu_codec) {
        if (profile.codec == "av1_cpu") {
            if (profile.preset < 0 || profile.preset > 13) {
                profile.preset = 4;
            }
        } else {
            // hevc_cpu
            if (profile.preset < 0 || profile.preset > 9) {
                profile.preset = 5;
            }
        }
    } else {
        if (profile.preset < 1 || profile.preset > 7) {
            profile.preset = 5;
        }
    }

    if (profile.rate_control.empty() || profile.rate_control == "0") {
        profile.rate_control = is_cpu_codec ? "crf" : "cq";
    } else if (profile.rate_control == "1") {
        profile.rate_control = "vbr";
    } else if (profile.rate_control == "constqp" || profile.rate_control == "2") {
        profile.rate_control = "qp";
    } else if (profile.rate_control == "3") {
        profile.rate_control = "cq";
    } else if (profile.rate_control == "4") {
        profile.rate_control = "crf";
    }

    if (profile.rate_control != "cbr" && profile.rate_control != "vbr" &&
        profile.rate_control != "qp" && profile.rate_control != "cq" &&
        profile.rate_control != "crf") {
        return err(ErrorCode::InvalidArgument,
                   "profile.rateControl must be one of ['cbr', 'cq', 'crf', 'qp', 'vbr']");
    }

    if (is_cpu_codec && profile.rate_control == "cq") {
        profile.rate_control = "crf";
    } else if (!is_cpu_codec && profile.rate_control == "crf") {
        profile.rate_control = "cq";
    }

    if (profile.bitrate_kbps < 0 || profile.bitrate_kbps > 200000) {
        return err(ErrorCode::InvalidArgument, "profile.bitrateKbps must be in 0..200000");
    }
    if (profile.qp < 0 || profile.qp > 51) {
        return err(ErrorCode::InvalidArgument, "profile.qp must be in 0..51");
    }

    if (profile.resolution.empty()) {
        profile.resolution = "4k";
    }
    if (profile.resolution == "4k") {
        if (profile.target_width <= 0 && profile.target_height <= 0) {
            profile.target_width = 3840;
            profile.target_height = 2160;
        }
    } else if (profile.resolution == "2k") {
        profile.target_width = 2560;
        profile.target_height = 1440;
    } else if (profile.resolution == "fhd") {
        profile.target_width = 1920;
        profile.target_height = 1080;
    } else if (profile.resolution == "native") {
        profile.target_width = 0;
        profile.target_height = 0;
    } else {
        return err(ErrorCode::InvalidArgument,
                   "profile.resolution must be one of ['2k', '4k', 'fhd', 'native']");
    }

    if (profile.target_width < 0 || profile.target_height < 0) {
        return err(ErrorCode::InvalidArgument, "target geometry must be non-negative");
    }

    if (profile.geometry.empty()) {
        profile.geometry = "auto";
    }
    if (profile.geometry != "auto" && profile.geometry != "pillarbox") {
        return err(ErrorCode::InvalidArgument,
                   "profile.geometry must be one of ['auto', 'pillarbox']");
    }

    if (profile.vsr_quality < 1 || profile.vsr_quality > 4) {
        return err(ErrorCode::InvalidArgument, "profile.vsrQuality must be in 1..4");
    }
    if (profile.peak_nits < 400 || profile.peak_nits > 4000) {
        return err(ErrorCode::InvalidArgument, "profile.peakNits must be in 400..4000");
    }

    if (profile.fps_mode.empty()) {
        profile.fps_mode = "60-nvofa";
    }
    if (profile.fps_mode != "original" && profile.fps_mode != "60-nvofa" &&
        profile.fps_mode != "120-nvofa" && profile.fps_mode != "60-rife" &&
        profile.fps_mode != "120-rife") {
        return err(ErrorCode::InvalidArgument,
                   "profile.fpsMode must be one of ['120-nvofa', '120-rife', '60-nvofa', '60-rife', 'original']");
    }

    if (profile.fps_mode == "60-rife" || profile.fps_mode == "120-rife") {
        const std::filesystem::path resolved_rife = resolveDefaultRifeEnginePath(profile.rife_engine);
        profile.rife_engine = pathToUtf8(resolved_rife);
    }

    if (profile.gpu < 0) {
        return err(ErrorCode::InvalidArgument, "profile.gpu must be >= 0");
    }
    if (profile.frames < 0) {
        return err(ErrorCode::InvalidArgument, "profile.frames must be >= 0");
    }

    profile.output = deriveOutputPath(profile.input, profile.codec, profile.output, profile.auto_output);

    if (require_io_paths) {
        if (profile.input.empty()) {
            return err(ErrorCode::InvalidArgument, "profile.input is required");
        }
        if (profile.output.empty()) {
            return err(ErrorCode::InvalidArgument, "profile.output is required");
        }
        if (profile.input == profile.output) {
            return err(ErrorCode::InvalidArgument,
                       "input and output paths must not be identical");
        }
    }

    return {};
}

HwTranscodeOptions profileToHwOptions(const TranscodeProfile& profile) {
    const bool is_cpu = (profile.codec == "av1_cpu" || profile.codec == "hevc_cpu");
    const VideoCodec codec = (profile.codec == "hevc" || profile.codec == "hevc_cpu") ? VideoCodec::HEVC : VideoCodec::AV1;
    int rc = 3;
    if (profile.rate_control == "cq") {
        rc = 3;
    } else if (profile.rate_control == "crf") {
        rc = 4;
    } else if (profile.rate_control == "qp") {
        rc = 2;
    } else if (profile.rate_control == "vbr") {
        rc = 1;
    } else if (profile.rate_control == "cbr") {
        rc = 0;
    }
    const int geom = (profile.geometry == "pillarbox") ? 1 : 0;
    const bool vsr_before_fg = (profile.pipeline_order != "fg-first");

    bool fruc = true;
    Rational fps{60, 1};
    std::filesystem::path rife_path;
    if (profile.fps_mode == "original") {
        fruc = false;
        fps = Rational{0, 1};
    } else if (profile.fps_mode == "120-nvofa") {
        fruc = true;
        fps = Rational{120, 1};
    } else if (profile.fps_mode == "60-rife") {
        fruc = true;
        fps = Rational{60, 1};
        rife_path = resolveDefaultRifeEnginePath(profile.rife_engine);
    } else if (profile.fps_mode == "120-rife") {
        fruc = true;
        fps = Rational{120, 1};
        rife_path = resolveDefaultRifeEnginePath(profile.rife_engine);
    } else {
        fruc = true;
        fps = Rational{60, 1};
        if (!profile.rife_engine.empty()) {
            rife_path = utf8ToPath(profile.rife_engine);
        }
    }

    return HwTranscodeOptions{
        .input_path = utf8ToPath(profile.input),
        .output_path = utf8ToPath(profile.output),
        .frame_limit = profile.frames,
        .codec = codec,
        .use_cpu_encoder = is_cpu,
        .cpu_preset = std::to_string(profile.preset),
        .bitrate_kbps = profile.bitrate_kbps,
        .preset = profile.preset,
        .rate_control = rc,
        .qp = profile.qp,
        .copy_audio = profile.copy_audio,
        .vsr_before_fg = vsr_before_fg,
        .hdr10plus = profile.hdr10plus,
        .lut_path = profile.lut.empty() ? std::filesystem::path{} : utf8ToPath(profile.lut),
        .target_width = profile.target_width,
        .target_height = profile.target_height,
        .vsr_enabled = profile.vsr_enabled,
        .vsr_quality = profile.vsr_quality,
        .peak_nits = profile.peak_nits,
        .geometry_mode = geom,
        .device_index = profile.gpu,
        .fruc_enabled = fruc,
        .target_fps = fps,
        .rife_engine_path = std::move(rife_path),
    };
}

Result<TranscodeProfile> parseProfileFromJson(std::string_view json_text) {
    const std::string trimmed = trimAscii(json_text);
    if (trimmed.empty() || trimmed.front() != '{') {
        return err(ErrorCode::InvalidArgument, "JSON payload must be an object");
    }

    TranscodeProfile p{};
    const std::string_view ui_slice = extractJsonObjectSlice(trimmed, "ui");
    if (!ui_slice.empty()) {
        bool auto_out = true;
        auto r = extractJsonBool(ui_slice, "autoOutput", auto_out);
        if (!r.has_value()) return std::unexpected(r.error());
        if (r.value()) p.auto_output = auto_out;

        std::string lang_str;
        if (extractJsonString(ui_slice, "lang", lang_str)) {
            if (auto parsed_lang = parseLanguage(lang_str); parsed_lang.has_value()) {
                setLanguage(parsed_lang.value());
            }
        }
    }

    std::string_view scope = extractJsonObjectSlice(trimmed, "profile");
    if (scope.empty()) {
        scope = trimmed;
    }

    (void)extractJsonString(scope, "input", p.input);
    (void)extractJsonString(scope, "output", p.output);
    (void)extractJsonString(scope, "codec", p.codec);
    (void)extractJsonString(scope, "rateControl", p.rate_control);
    (void)extractJsonString(scope, "resolution", p.resolution);
    (void)extractJsonString(scope, "geometry", p.geometry);
    (void)extractJsonString(scope, "fpsMode", p.fps_mode);
    (void)extractJsonString(scope, "pipelineOrder", p.pipeline_order);
    if (p.pipeline_order.empty()) {
        (void)extractJsonString(scope, "pipeline_order", p.pipeline_order);
    }
    (void)extractJsonString(scope, "rifeEngine", p.rife_engine);
    (void)extractJsonString(scope, "lut", p.lut);

    auto checkInt = [&](std::string_view key, int& dst) -> Result<void> {
        auto r = extractJsonInt(scope, key, dst);
        if (!r.has_value()) return std::unexpected(r.error());
        return {};
    };
    auto checkBool = [&](std::string_view key, bool& dst) -> Result<void> {
        auto r = extractJsonBool(scope, key, dst);
        if (!r.has_value()) return std::unexpected(r.error());
        return {};
    };

    if (auto r = checkInt("preset", p.preset); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("bitrateKbps", p.bitrate_kbps); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("qp", p.qp); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("vsrQuality", p.vsr_quality); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("peakNits", p.peak_nits); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("gpu", p.gpu); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkInt("frames", p.frames); !r.has_value()) return std::unexpected(r.error());

    if (auto r = checkBool("vsrEnabled", p.vsr_enabled); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkBool("copyAudio", p.copy_audio); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkBool("hdr10plus", p.hdr10plus); !r.has_value()) return std::unexpected(r.error());
    if (auto r = checkBool("autoOutput", p.auto_output); !r.has_value()) return std::unexpected(r.error());

    std::string cpu_preset_str;
    if (extractJsonString(scope, "cpuPreset", cpu_preset_str) && !cpu_preset_str.empty()) {
        if (p.codec == "av1_cpu" || p.codec == "hevc_cpu") {
            int cp_val = 0;
            if (auto r = extractJsonInt(scope, "cpuPreset", cp_val); r.has_value()) {
                p.preset = cp_val;
            } else {
                static constexpr std::array<std::string_view, 10> kX265Presets = {
                    "ultrafast", "superfast", "veryfast", "faster", "fast",
                    "medium", "slow", "slower", "veryslow", "placebo"
                };
                for (size_t idx = 0; idx < kX265Presets.size(); ++idx) {
                    if (cpu_preset_str == kX265Presets[idx]) {
                        p.preset = static_cast<int>(idx);
                        break;
                    }
                }
            }
        }
    }

    return p;
}

std::string profileToJson(const TranscodeProfile& p) {
    return std::format(
        "{{\n"
        "    \"input\": \"{}\",\n"
        "    \"output\": \"{}\",\n"
        "    \"codec\": \"{}\",\n"
        "    \"preset\": {},\n"
        "    \"rateControl\": \"{}\",\n"
        "    \"bitrateKbps\": {},\n"
        "    \"qp\": {},\n"
        "    \"resolution\": \"{}\",\n"
        "    \"geometry\": \"{}\",\n"
        "    \"vsrEnabled\": {},\n"
        "    \"vsrQuality\": {},\n"
        "    \"peakNits\": {},\n"
        "    \"fpsMode\": \"{}\",\n"
        "    \"pipelineOrder\": \"{}\",\n"
        "    \"rifeEngine\": \"{}\",\n"
        "    \"copyAudio\": {},\n"
        "    \"hdr10plus\": {},\n"
        "    \"lut\": \"{}\",\n"
        "    \"gpu\": {},\n"
        "    \"frames\": {}\n"
        "  }}",
        escapeJson(p.input), escapeJson(p.output), escapeJson(p.codec), p.preset,
        escapeJson(p.rate_control), p.bitrate_kbps, p.qp, escapeJson(p.resolution),
        escapeJson(p.geometry), p.vsr_enabled ? "true" : "false", p.vsr_quality,
        p.peak_nits, escapeJson(p.fps_mode), escapeJson(p.pipeline_order), escapeJson(p.rife_engine),
        p.copy_audio ? "true" : "false", p.hdr10plus ? "true" : "false",
        escapeJson(p.lut), p.gpu, p.frames);
}

std::string exportSchemaJson() {
    const TranscodeProfile defaults{};
    std::string out = "{\n  \"version\": 1,\n  \"defaults\": ";
    out += profileToJson(defaults);
    out += ",\n  \"params\": [\n";
    for (size_t i = 0; i < kParamSchema.size(); ++i) {
        const ParamMeta& m = kParamSchema[i];
        const char* kind_str = (m.kind == ParamKind::Int) ? "int"
                             : (m.kind == ParamKind::Bool) ? "bool"
                             : (m.kind == ParamKind::Enum) ? "enum" : "string";
        out += std::format(
            "    {{\"key\": \"{}\", \"cli\": \"{}\", \"type\": \"{}\", \"labelId\": \"{}\"",
            m.json_key, m.cli_flag, kind_str, strIdName(m.label_id));
        if (m.kind == ParamKind::Int) {
            out += std::format(", \"min\": {}, \"max\": {}, \"default\": {}",
                               m.min_val, m.max_val, m.default_int);
        } else if (m.kind == ParamKind::Bool) {
            out += std::format(", \"default\": {}", m.default_bool ? "true" : "false");
        } else if (m.kind == ParamKind::Enum) {
            out += std::format(", \"default\": \"{}\", \"options\": [", m.default_str);
            std::string_view csv = m.enum_csv;
            bool first = true;
            while (!csv.empty()) {
                const size_t comma = csv.find(',');
                const std::string_view token = (comma == std::string_view::npos) ? csv : csv.substr(0, comma);
                if (!first) out += ", ";
                out += std::format("\"{}\"", token);
                first = false;
                if (comma == std::string_view::npos) break;
                csv.remove_prefix(comma + 1);
            }
            out += "]";
        } else {
            out += std::format(", \"default\": \"{}\"", m.default_str);
        }
        out += (i + 1 < kParamSchema.size()) ? "},\n" : "}\n";
    }
    out += "  ],\n  \"i18n\": ";
    out += exportI18nJson();
    out += "\n}\n";
    return out;
}

