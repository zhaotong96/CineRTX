std::string toLowerAscii(std::string_view text) {
    std::string out;
    out.reserve(text.size());
    for (const char c : text) {
        out.push_back(static_cast<char>(
            (c >= 'A' && c <= 'Z') ? (c + ('a' - 'A')) : c));
    }
    return out;
}

std::string trimAscii(std::string_view text) {
    size_t first = 0;
    while (first < text.size() &&
           (text[first] == ' ' || text[first] == '\t' ||
            text[first] == '\r' || text[first] == '\n')) {
        ++first;
    }
    size_t last = text.size();
    while (last > first &&
           (text[last - 1] == ' ' || text[last - 1] == '\t' ||
            text[last - 1] == '\r' || text[last - 1] == '\n')) {
        --last;
    }
    return std::string(text.substr(first, last - first));
}

std::string escapeJson(std::string_view input) {
    std::string out;
    out.reserve(input.size() + 8);
    for (const char raw : input) {
        const unsigned char c = static_cast<unsigned char>(raw);
        if (c == '"') {
            out += "\\\"";
        } else if (c == '\\') {
            out += "\\\\";
        } else if (c == '\n') {
            out += "\\n";
        } else if (c == '\r') {
            out += "\\r";
        } else if (c == '\t') {
            out += "\\t";
        } else if (c < 0x20) {
            char buf[8] = {};
            std::snprintf(buf, sizeof(buf), "\\u%04x", c);
            out += buf;
        } else {
            out.push_back(raw);
        }
    }
    return out;
}

std::filesystem::path executableDirectory() {
#if defined(_WIN32)
    wchar_t buffer[MAX_PATH] = {};
    const DWORD len = ::GetModuleFileNameW(nullptr, buffer, MAX_PATH);
    if (len > 0 && len < MAX_PATH) {
        return std::filesystem::path(buffer).parent_path();
    }
#endif
    std::error_code ec;
    const auto cwd = std::filesystem::current_path(ec);
    return ec ? std::filesystem::path{} : cwd;
}

std::string pathToUtf8(const std::filesystem::path& p) {
    const std::u8string u8 = p.u8string();
    return std::string(reinterpret_cast<const char*>(u8.data()), u8.size());
}

std::filesystem::path utf8ToPath(std::string_view s) {
    const std::u8string_view u8(reinterpret_cast<const char8_t*>(s.data()), s.size());
    return std::filesystem::path(u8);
}

bool isAutoGeneratedOutputName(std::string_view path_str) {
    if (path_str.empty()) {
        return true;
    }
    const std::filesystem::path p = utf8ToPath(path_str);
    const std::string filename = toLowerAscii(pathToUtf8(p.filename()));
    static constexpr std::string_view kSuffixes[] = {
        "_remaster_av1.mp4",      "_remaster_hevc.mp4",      "_remaster_h264.mp4",
        "_remaster_av1_cpu.mp4",  "_remaster_hevc_cpu.mp4",
        "_remaster_av1.mkv",      "_remaster_hevc.mkv",      "_remaster_h264.mkv",
        "_remaster_av1_cpu.mkv",  "_remaster_hevc_cpu.mkv",
    };
    for (std::string_view suffix : kSuffixes) {
        if (filename.size() > suffix.size() &&
            filename.compare(filename.size() - suffix.size(), suffix.size(), suffix) == 0) {
            return true;
        }
    }
    return false;
}

// Minimal, zero-dependency JSON field extractor for flat/nested profile objects.
size_t findJsonKeyValueStart(std::string_view json, std::string_view key) {
    const std::string pattern = std::string("\"") + std::string(key) + "\"";
    size_t pos = 0;
    while ((pos = json.find(pattern, pos)) != std::string_view::npos) {
        size_t after = pos + pattern.size();
        while (after < json.size() &&
               (json[after] == ' ' || json[after] == '\t' ||
                json[after] == '\r' || json[after] == '\n')) {
            ++after;
        }
        if (after < json.size() && json[after] == ':') {
            ++after;
            while (after < json.size() &&
                   (json[after] == ' ' || json[after] == '\t' ||
                    json[after] == '\r' || json[after] == '\n')) {
                ++after;
            }
            return after;
        }
        pos += pattern.size();
    }
    return std::string_view::npos;
}

bool extractJsonString(std::string_view json, std::string_view key, std::string& out) {
    size_t pos = findJsonKeyValueStart(json, key);
    if (pos == std::string_view::npos || pos >= json.size() || json[pos] != '"') {
        return false;
    }
    ++pos;
    std::string result;
    while (pos < json.size()) {
        const char c = json[pos++];
        if (c == '"') {
            out = std::move(result);
            return true;
        }
        if (c == '\\' && pos < json.size()) {
            const char esc = json[pos++];
            switch (esc) {
                case '"':  result.push_back('"'); break;
                case '\\': result.push_back('\\'); break;
                case '/':  result.push_back('/'); break;
                case 'n':  result.push_back('\n'); break;
                case 'r':  result.push_back('\r'); break;
                case 't':  result.push_back('\t'); break;
                default:   result.push_back(esc); break;
            }
        } else {
            result.push_back(c);
        }
    }
    return false;
}

Result<bool> extractJsonInt(std::string_view json, std::string_view key, int& out) {
    size_t pos = findJsonKeyValueStart(json, key);
    if (pos == std::string_view::npos || pos >= json.size()) {
        return false;
    }
    if (json.substr(pos, 4) == "null") {
        return false;
    }
    if (json[pos] == '"') {
        std::string str_val;
        if (!extractJsonString(json, key, str_val)) {
            return err(ErrorCode::InvalidArgument,
                       std::format("profile.{} must be an integer", key));
        }
        int parsed = 0;
        const auto [ptr, ec] = std::from_chars(
            str_val.data(), str_val.data() + str_val.size(), parsed);
        if (ec != std::errc{} || ptr != str_val.data() + str_val.size()) {
            return err(ErrorCode::InvalidArgument,
                       std::format("profile.{} must be an integer", key));
        }
        out = parsed;
        return true;
    }
    size_t end = pos;
    if (end < json.size() && (json[end] == '-' || json[end] == '+')) {
        ++end;
    }
    while (end < json.size() && std::isdigit(static_cast<unsigned char>(json[end]))) {
        ++end;
    }
    if (end == pos || (end < json.size() && json[end] == '.')) {
        return err(ErrorCode::InvalidArgument,
                   std::format("profile.{} must be an integer", key));
    }
    int parsed = 0;
    const auto [ptr, ec] = std::from_chars(json.data() + pos, json.data() + end, parsed);
    if (ec != std::errc{} || ptr != json.data() + end) {
        return err(ErrorCode::InvalidArgument,
                   std::format("profile.{} must be an integer", key));
    }
    out = parsed;
    return true;
}

Result<bool> extractJsonBool(std::string_view json, std::string_view key, bool& out) {
    size_t pos = findJsonKeyValueStart(json, key);
    if (pos == std::string_view::npos || pos >= json.size()) {
        return false;
    }
    if (json.substr(pos, 4) == "true") {
        out = true;
        return true;
    }
    if (json.substr(pos, 5) == "false") {
        out = false;
        return true;
    }
    if (json[pos] == '1') {
        out = true;
        return true;
    }
    if (json[pos] == '0') {
        out = false;
        return true;
    }
    return err(ErrorCode::InvalidArgument,
               std::format("profile.{} must be a boolean", key));
}

std::string_view extractJsonObjectSlice(std::string_view json, std::string_view key) {
    size_t pos = findJsonKeyValueStart(json, key);
    if (pos == std::string_view::npos || pos >= json.size() || json[pos] != '{') {
        return {};
    }
    size_t depth = 0;
    bool in_string = false;
    for (size_t i = pos; i < json.size(); ++i) {
        const char c = json[i];
        if (in_string) {
            if (c == '\\' && i + 1 < json.size()) {
                ++i;
            } else if (c == '"') {
                in_string = false;
            }
            continue;
        }
        if (c == '"') {
            in_string = true;
        } else if (c == '{') {
            ++depth;
        } else if (c == '}') {
            --depth;
            if (depth == 0) {
                return json.substr(pos, i - pos + 1);
            }
        }
    }
    return {};
}

